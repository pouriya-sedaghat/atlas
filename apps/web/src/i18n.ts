export const STRINGS = { fa, en };
export type Strings = typeof fa;

const nfFa = new Intl.NumberFormat('fa-IR', { maximumFractionDigits: 2 });
const nfEn = new Intl.NumberFormat('en-US', { maximumFractionDigits: 2 });

export function fmtDistance(m: number | null | undefined, lang: UiLang): string {
  if (m === null || m === undefined) return '—';
  const nf = lang === 'fa' ? nfFa : nfEn;
  return m >= 1000 ? `${nf.format(m / 1000)} ${lang === 'fa' ? 'کیلومتر' : 'km'}` : `${nf.format(m)} ${lang === 'fa' ? 'متر' : 'm'}`;
}

export function fmtDuration(s: number | null | undefined, lang: UiLang): string {
  if (s === null || s === undefined) return '—';
  const nf = lang === 'fa' ? nfFa : nfEn;
  return s >= 60 ? `${nf.format(s / 60)} ${lang === 'fa' ? 'دقیقه' : 'min'}` : `${nf.format(s)} ${lang === 'fa' ? 'ثانیه' : 's'}`;
}
